"""Generate model_tables.md from model_outputs.json (run after toing_model.py)."""
import json, io, pathlib
HERE = pathlib.Path(__file__).parent
O = json.load(open(HERE / "model_outputs.json", encoding="utf-8"))
f = lambda v, d=1: ("−" if v < 0 else "") + f"{abs(v):,.{d}f}"
t = O["toing"]; c = O["core"]
L = ["# Toing model tables (generated by toing_model.py)", ""]
L += ["## T1 Per-order stack today, ₹ (Toing ₹99 vs core ₹700)", "", "| Line | Toing ₹99 | Core ₹700 |", "|---|---|---|"]
rows = [("Customer pays", t["cust"], 700), ("Restaurant keeps (after commission, GST on commission, ads)", t["rest_keeps"], None),
        ("Swiggy revenue", t["rev"], c["rev"]), ("Rider pay", -t["rider"], -c["rider"]), ("Insurance", -t["ins"], -1),
        ("CoSS contribution", -t["coss"], -c["coss"]), ("Payments", -t["pg"], -c["pg"]), ("Support and refunds", -t["sup"], -c["sup"]),
        ("Coupons", -t["disc"], -c["disc"]), ("Tech", -t["tech"], -1), ("Contribution", t["contrib"], c["cm"]),
        ("Overheads", None, -c["ovh"]), ("Adjusted EBITDA", None, c["ebitda"])]
for lab, a, b in rows:
    L.append(f"| {lab} | {f(a) if a is not None else 'n/a'} | {f(b) if b is not None else 'n/a'} |")
L += ["", "## T2 Lever bridge, contribution per ₹99 order, ₹", "", "| Lever | Who controls | Change | After |", "|---|---|---|---|",
      f"| Today | | | {f(O['bridge']['start'], 2)} |"]
for s in O["bridge"]["steps"]:
    L.append(f"| {s['lever']} | {s['who']} | +{f(s['delta'], 2)} | {f(s['after'], 2)} |")
L += ["", "## T3 Density curve, ₹ per Drop order", "", "| Meals per run | Rider cost per meal | Contribution |", "|---|---|---|"]
for d in O["density"]:
    L.append(f"| {d['n']} | {f(d['rider'], 1)} | {f(d['contrib'], 1)} |")
L += ["", "## T4 Triangulation of Toing's quarter", "", "| Item | Value |", "|---|---|"]
for k, v in O["tri"].items():
    L.append(f"| {k} | {f(v, 2)} |")
fn = O["funnel"]
L += ["", "## T5 Funnel", "", "| Horizon (months) | Cost per user ₹ | Migration needed, CAC lens % | LTV lens % |", "|---|---|---|---|"]
for r in fn["rows"]:
    L.append(f"| {r['T']} | {f(r['cost_per_user'], 0)} | {f(100 * r['m_cac'], 0)} | {f(100 * r['m_ltv'], 0)} |")
L += ["", f"Loss a month per user ₹{f(fn['loss_per_user_month'], 0)}; core LTV ₹{f(fn['ltv_core'], 0)}; cost per incremental user ₹{f(fn['cost_per_incr_12m'], 0)}; {f(fn['multiple_vs_cac'], 1)}x paid CAC.",
      "", "### Migration needed (%) by paid CAC and incremental share", "", "| CAC ₹ | 33% new | 50% | 67% | 100% |", "|---|---|---|---|---|"]
for cac, row in fn["grid_m_cac_pct"].items():
    L.append(f"| {cac} | " + " | ".join(str(row[k]) for k in ("0.33", "0.5", "0.67", "1.0")) + " |")
L += ["", "## T6 Three-year paths, ₹ Cr", "", "| Scenario | Path | Y1 | Y2 | Y3 | Total |", "|---|---|---|---|---|---|"]
for sc in ("bear", "base", "bull"):
    p = O["paths"][sc]
    for k, n in [("S", "Scale as it runs"), ("F", "Funnel (CAC credit)"), ("F_ltv", "Funnel (LTV credit)"), ("K", "Kill"), ("R", "Rebuild"), ("R_fail", "Rebuild, gate fails")]:
        v = p[k]; L.append(f"| {sc} | {n} | {f(v[0], 0)} | {f(v[1], 0)} | {f(v[2], 0)} | {f(p['cum'][k], 0)} |")
L += ["", "## T7 Decomposition of the gap, Rebuild vs Scale (base), ₹ Cr", "", "| Component | ₹ Cr |", "|---|---|"]
for k, v in O["decomp"].items():
    L.append(f"| {k} | {f(v, 0)} |")
L += ["", f"## T8 Tornado on blended contribution per order (base {f(O['tornado']['base'], 2)})", "", "| Driver | Low case | High case |", "|---|---|---|"]
for r in O["tornado"]["rows"]:
    L.append(f"| {r['label']} ({r['lo_in']} / {r['hi_in']}) | {f(r['lo'], 1)} | {f(r['hi'], 1)} |")
L += ["", "## T9 Flip points (Rebuild equals Kill over 3 years)", "", "| Input | Flip value |", "|---|---|"]
for k, v in O["flip"].items():
    L.append(f"| {k} | {v} |")
L += ["", "## T10 Stress tests: 3-year totals ₹ Cr (Rebuild R, Scale S, Funnel with LTV credit F, Kill K)", "",
      "| Input | Value | R | S | F | K | R beats S and F |", "|---|---|---|---|---|---|---|"]
for k, rows_ in O["robust"].items():
    for r in rows_:
        L.append(f"| {k} | {r['v']} | {r['R']} | {r['S']} | {r['F']} | {r['K']} | {r['R_beats_S_F']} |")
rg = O["reg"]
L += ["", "## T11 Regulatory cost per order, ₹", "", "| Item | Toing ₹99 | Core ₹700 |", "|---|---|---|",
      f"| CoSS contribution (1.5% of revenue, cap 5% of rider pay) | {f(rg['coss_toing'], 2)} | {f(rg['coss_core'], 2)} |",
      f"| Karnataka fee (cap) | {f(rg['ka_fee'], 2)} | {f(rg['ka_fee'], 2)} |",
      f"| As % of basket | {f(rg['pct_gov_toing'], 2)} | {f(rg['pct_gov_core'], 2)} |",
      f"| CoSS if levied on customer-paid turnover (upper bound) | {f(rg['coss_toing_gov_basis'], 2)} | n/a |"]
io.open(HERE / "model_tables.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
print(len(L), "lines")
