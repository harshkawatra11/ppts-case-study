def new_sheet(name):
    return wb.create_sheet(name)


def autosize(ws, widths=None):
    if widths:
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(i)].width = w
        return
    for col in ws.columns:
        length = max((len(str(c.value)) for c in col if c.value is not None), default=8)
        ws.column_dimensions[col[0].column_letter].width = min(max(length + 2, 10), 60)


def write_header(ws, headers, row=1):
    for j, h in enumerate(headers, start=1):
        c = ws.cell(row=row, column=j, value=h)
        c.font = HEAD_FONT
        c.fill = HEAD_FILL


def dump_rows(ws, headers, rows, start_row=1):
    write_header(ws, headers, start_row)
    for i, r in enumerate(rows, start=start_row + 1):
        for j, h in enumerate(headers, start=1):
            ws.cell(row=i, column=j, value=r.get(h) if isinstance(r, dict) else r[j - 1])
    return start_row + len(rows)


